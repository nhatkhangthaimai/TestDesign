export async function run() {
  console.log("================================================================================");
  console.log("   ĐANG NẠP TOÀN BỘ DANH MỤC SẢN PHẨM CÔNG NGHỆ CHÍNH HÃNG VÀO DATABASE...     ");
  console.log("================================================================================");

  const categories = await prisma.category.findMany();
  const catMap = new Map(categories.map((c) => [c.slug, c.id]));
  const brands = await prisma.brand.findMany();
  const brandMap = new Map(brands.map((b) => [b.slug, b.id]));

  let inserted = 0;
  let updated = 0;

  for (const item of CATALOG) {
    const categoryId = catMap.get(item.categorySlug);
    const brandId = brandMap.get(item.brandSlug);
    if (!categoryId || !brandId) continue;

    const data = {
      title: item.title,
      slug: item.slug,
      sku: item.sku,
      description: item.description,
      content: item.content,
      regularPrice: item.regularPrice,
      salePrice: item.salePrice || null,
      stock: item.stock,
      isFeatured: item.isFeatured || false,
      isBestSeller: item.isBestSeller || false,
      isNewArrival: item.isNewArrival || false,
      isFlashSale: item.isFlashSale || false,
      ratingsAvg: item.ratingsAvg,
      ratingsCount: item.ratingsCount,
      categoryId,
      brandId,
    };

    const ex = await prisma.product.findUnique({ where: { slug: item.slug } });
    let pId = "";
    if (ex) {
      await prisma.product.update({ where: { id: ex.id }, data });
      pId = ex.id;
      updated++;
    } else {
      const cr = await prisma.product.create({ data });
      pId = cr.id;
      inserted++;
    }

    const img = await prisma.productImage.findFirst({ where: { productId: pId, isPrimary: true } });
    if (!img) {
      await prisma.productImage.create({
        data: { productId: pId, url: item.imageUrl, isPrimary: true, sortOrder: 0 }
      });
    }

    for (const s of item.specs) {
      const exSp = await prisma.productSpecification.findFirst({ where: { productId: pId, specKey: s.specKey } });
      if (!exSp) {
        await prisma.productSpecification.create({
          data: { productId: pId, groupName: s.groupName, specKey: s.specKey, specValue: s.specValue }
        });
      }
    }
  }

  const finalTotal = await prisma.product.count();
  console.log(`✓ Đã thêm mới: ${inserted} sản phẩm`);
  console.log(`✓ Đã cập nhật: ${updated} sản phẩm`);
  console.log(`✓ TỔNG CỘNG SẢN PHẨM TRONG DATABASE: ${finalTotal} SẢN PHẨM!`);
  console.log("================================================================================");
}

run().catch(console.error).finally(() => prisma.$disconnect());
